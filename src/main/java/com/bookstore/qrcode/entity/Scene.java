package com.bookstore.qrcode.entity;

/**
 * 活码创建场景枚举。
 *
 * <p>不同场景对应不同的预期扫码率和扩容策略，
 * 用于创建活码时自动计算初始接待员数量。</p>
 *
 * <p><b>注意：</b>此枚举为占位定义，完整的功能逻辑将在后续任务中实现。</p>
 */
public enum Scene {
    /** 日常推送：二维码发到家长群，长期有效，预期扫码率约 10% */
    daily_push,
    /** 家长会：现场集中扫码，短期高并发，预期扫码率约 60% */
    parent_meeting
}
